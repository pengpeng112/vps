-- 0002: 运行态账号权限（迁移账号执行；任务书 §19.4）
-- 运行态账号 mgmt_app 对业务表有 DML，但对 audit_log 仅 INSERT/SELECT。
GRANT USAGE ON SCHEMA public TO mgmt_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO mgmt_app;
REVOKE UPDATE, DELETE ON TABLE audit_log FROM mgmt_app;
GRANT SELECT, INSERT ON TABLE audit_log TO mgmt_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO mgmt_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO mgmt_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT USAGE, SELECT ON SEQUENCES TO mgmt_app;
-- 未来迁移新建的 audit_log 仍不可改写
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    REVOKE UPDATE, DELETE ON TABLES FROM mgmt_app;
